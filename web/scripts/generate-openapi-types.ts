/** Generate contracts directly from the current Rust API definitions. */
import { spawnSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const webDir = dirname(dirname(fileURLToPath(import.meta.url)))
const check = process.argv.includes('--check')
const banner = '// AUTO-GENERATED by bun run openapi — DO NOT EDIT MANUALLY\n/* eslint-disable style/indent, style/member-delimiter-style, style/quotes, style/semi */\n'
const surfaces = { admin: '/admin/api', user: '/api' } as const
const specs: Partial<Record<keyof typeof surfaces, any>> = {}

function writeOrCheck(path: string, content: string) {
  if (check) {
    if (readFileSync(path, 'utf8') !== content)
      throw new Error(`Stale API contract: ${path}. Run bun run openapi.`)
  }
  else {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, content)
  }
}

for (const surface of ['admin', 'user'] as const) {
  const result = spawnSync('cargo', ['run', '--quiet', '--locked', '--all-features', '-p', 'gated-admin', '--bin', 'gated-admin', '--', surface], {
    cwd: dirname(webDir),
    env: { ...process.env, CARGO_BUILD_TARGET: process.env.CARGO_BUILD_TARGET ?? 'x86_64-unknown-linux-gnu' },
    encoding: 'utf8',
    timeout: 300_000,
    maxBuffer: 16 * 1024 * 1024,
  })
  if (result.error || result.status !== 0)
    throw new Error(result.error?.message ?? result.stderr)
  const spec = JSON.parse(result.stdout)
  specs[surface] = spec
  const outputs = new Map([
    [join(webDir, 'scripts/openapi', `${surface}.snapshot.json`), `${JSON.stringify(spec, null, 2)}\n`],
    [join(webDir, 'src/shared/lib/api', `${surface}.types.ts`), banner + astToString(await openapiTS(spec))],
  ])
  for (const [path, content] of outputs)
    writeOrCheck(path, content)
  console.log(`[openapi] ${surface}: ${check ? 'verified' : 'generated'}`)
}

// The operation index in docs/api.md (and its Chinese translation) is
// generated from the same specs so the hand-written reference cannot silently
// miss an endpoint.
const BEGIN = '<!-- BEGIN GENERATED OPERATION INDEX: bun run openapi -->'
const END = '<!-- END GENERATED OPERATION INDEX -->'
const tables: Record<keyof typeof surfaces, string[]> = { admin: [], user: [] }
for (const surface of ['user', 'admin'] as const) {
  const prefix = surfaces[surface]
  const rows: string[] = []
  for (const [path, ops] of Object.entries<Record<string, any>>(specs[surface]?.paths ?? {})) {
    for (const [method, op] of Object.entries<any>(ops)) {
      const summary = (String(op.summary ?? '').split('\n')[0] ?? '').replaceAll('|', '\\|').trim()
      rows.push(`| ${method.toUpperCase()} | \`${prefix}${path.replaceAll(/\{(\w+)\}/g, ':$1')}\` | \`${op.operationId}\` | ${summary} |`)
    }
  }
  rows.sort()
  tables[surface] = ['| Method | Path | operationId | Summary |', '|---|---|---|---|', ...rows]
}
const docs = [
  {
    file: 'docs/api.md',
    heading: '## 7. OpenAPI operation index',
    intro: 'Generated by `bun run openapi` from the OpenAPI contracts exported from the Rust sources; do not edit by hand. CI checks it with `bun run openapi --check`. Request and response shapes are defined by `web/scripts/openapi/*.snapshot.json`.',
    titles: { user: 'User API `/api`', admin: 'Admin API `/admin/api`' },
  },
  {
    file: 'docs/api.zh-CN.md',
    heading: '## 7. OpenAPI 操作索引',
    intro: '由 `bun run openapi` 从 Rust 源码导出的 OpenAPI 契约生成，请勿手工编辑；CI 通过 `bun run openapi --check` 校验。请求与响应结构以 `web/scripts/openapi/*.snapshot.json` 为准。',
    titles: { user: '用户面 `/api`', admin: '管理面 `/admin/api`' },
  },
]
for (const { file, heading, intro, titles } of docs) {
  const lines = [BEGIN, '', heading, '', intro]
  for (const surface of ['user', 'admin'] as const)
    lines.push('', `### ${titles[surface]}`, '', ...tables[surface])
  lines.push('', END)
  const apiDocPath = join(dirname(webDir), file)
  const apiDoc = readFileSync(apiDocPath, 'utf8')
  const start = apiDoc.indexOf(BEGIN)
  const head = start === -1 ? `${apiDoc.trimEnd()}\n\n` : apiDoc.slice(0, start)
  const tail = start === -1 ? '\n' : apiDoc.slice(apiDoc.indexOf(END) + END.length)
  writeOrCheck(apiDocPath, `${head}${lines.join('\n')}${tail}`)
  console.log(`[openapi] ${file} operation index: ${check ? 'verified' : 'generated'}`)
}
